    ti.Name,
    NULL,
    RIGHT('0000000000' + CAST(@Last + ti.rn AS varchar(10)), 10),
    NULL,
    1,
    LEFT(REPLACE(CONVERT(varchar(36), NEWID()), '-', ''), 12),
    1,
    1,
    ti.CollectorId,
    @TenantId,
    @Now,
    @CreatedBy
FROM ToInsert ti;

