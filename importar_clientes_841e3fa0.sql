;WITH ToInsert AS (
    SELECT Name, CollectorId, ROW_NUMBER() OVER (ORDER BY Name) AS rn
    FROM #Decided WHERE Decision = 'INSERTAR'
)
INSERT INTO Bza_Customers
    (Name, FacebookName, Phone, Address, Status, PortalToken, IsPendingInfo, HasNoWhatsApp, BzaCollectorId, TenantId, CreatedAt, CreatedBy)
