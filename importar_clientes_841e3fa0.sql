/* Resolver recolector del tenant por nombre normalizado (UPPER + TRIM). */
IF OBJECT_ID('tempdb..#Decided') IS NOT NULL DROP TABLE #Decided;
;WITH ColUnique AS (
    SELECT UPPER(LTRIM(RTRIM(c.Name))) AS K, MIN(c.Id) AS Id, COUNT(*) AS Cnt
    FROM Bza_Collectors c
    WHERE c.TenantId = @TenantId
    GROUP BY UPPER(LTRIM(RTRIM(c.Name)))
)
SELECT
    i.Name,
    i.CollectorClean,
    cu.Id  AS CollectorId,
    cu.Cnt AS CollectorCnt,
    CASE
        WHEN cu.Id IS NULL THEN 'RECOLECTOR_NO_ENCONTRADO'
        WHEN cu.Cnt > 1  THEN 'RECOLECTOR_AMBIGUO'
        WHEN EXISTS (SELECT 1 FROM Bza_Customers x
                     WHERE x.TenantId = @TenantId
                       AND UPPER(LTRIM(RTRIM(x.Name))) = UPPER(LTRIM(RTRIM(i.Name)))) THEN 'YA_EXISTE'
        ELSE 'INSERTAR'
    END AS Decision
INTO #Decided
FROM #Incoming i
LEFT JOIN ColUnique cu ON cu.K = UPPER(LTRIM(RTRIM(i.CollectorClean)));

/* Asegurar la secuencia de placeholder del bazar. */
DECLARE @Last int;
SELECT @Last = LastNumber FROM Bza_NoWhatsAppSequences WHERE TenantId = @TenantId;
